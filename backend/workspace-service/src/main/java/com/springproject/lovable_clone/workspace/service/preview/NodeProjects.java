package com.springproject.lovable_clone.workspace.service.preview;

import com.springproject.lovable_clone.workspace.service.ProjectFileService.StoredFile;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.HashSet;
import java.util.HexFormat;
import java.util.List;
import java.util.Locale;
import java.util.Set;
import java.util.concurrent.TimeUnit;
import java.util.stream.Stream;

/** Writing a project to a folder and running npm in it, shared by the local preview and the build check. */
final class NodeProjects {

    static final boolean WINDOWS = System.getProperty("os.name", "").toLowerCase(Locale.ROOT).contains("win");
    // generated by npm, not part of the project files, kept between runs
    private static final Set<String> KEEP = Set.of("node_modules", "package-lock.json");

    private NodeProjects() {
    }

    /** Writes the files into dir and removes files that are no longer in the project (dependencies stay). */
    static void materialize(Path dir, List<StoredFile> files) {
        try {
            Files.createDirectories(dir);
            Set<Path> wanted = new HashSet<>();
            for (StoredFile file : files) {
                Path target = dir.resolve(file.path()).normalize();
                if (!target.startsWith(dir)) continue;
                Files.createDirectories(target.getParent());
                Files.write(target, file.content());
                wanted.add(target);
            }
            try (Stream<Path> walk = Files.walk(dir)) {
                walk.filter(Files::isRegularFile)
                        .filter(p -> !wanted.contains(p))
                        .filter(p -> !KEEP.contains(dir.relativize(p).getName(0).toString()))
                        .forEach(p -> p.toFile().delete());
            }
        } catch (IOException e) {
            throw new UncheckedIOException("Could not prepare project directory " + dir, e);
        }
    }

    /** Runs npm install unless node_modules already matches this package.json (marker in meta). */
    static void installDependencies(Path dir, Path meta) {
        try {
            Path packageJson = dir.resolve("package.json");
            if (!Files.exists(packageJson)) {
                throw new IllegalStateException("The project has no package.json");
            }
            String hash = sha256(Files.readAllBytes(packageJson));
            Path marker = meta.resolve("deps.sha256");
            if (Files.isDirectory(dir.resolve("node_modules")) && Files.exists(marker)
                    && hash.equals(Files.readString(marker).trim())) {
                return;
            }
            Path installLog = meta.resolve("install.log");
            Process install = launch(dir, installLog, "npm", "install", "--no-audit", "--no-fund", "--loglevel=error");
            if (!install.waitFor(10, TimeUnit.MINUTES)) {
                kill(install);
                throw new IllegalStateException("npm install timed out");
            }
            if (install.exitValue() != 0) {
                throw new IllegalStateException("npm install failed: " + tail(installLog));
            }
            Files.writeString(marker, hash);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            throw new IllegalStateException("Interrupted while installing dependencies");
        }
    }

    static Process launch(Path dir, Path log, String... command) {
        List<String> cmd = new ArrayList<>();
        if (WINDOWS) {
            cmd.add("cmd.exe");
            cmd.add("/c");
        }
        cmd.addAll(List.of(command));
        try {
            return new ProcessBuilder(cmd)
                    .directory(dir.toFile())
                    .redirectErrorStream(true)
                    .redirectOutput(log.toFile())
                    .start();
        } catch (IOException e) {
            throw new IllegalStateException("Could not run '" + String.join(" ", command)
                    + "'. Is Node.js installed and on the PATH?", e);
        }
    }

    static void kill(Process process) {
        process.descendants().forEach(ProcessHandle::destroyForcibly);
        process.destroyForcibly();
    }

    static String tail(Path log) {
        try {
            List<String> lines = Files.readAllLines(log, StandardCharsets.UTF_8);
            return String.join("\n", lines.subList(Math.max(0, lines.size() - 15), lines.size()));
        } catch (IOException e) {
            return "(no log)";
        }
    }

    static String sha256(byte[] data) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(data));
        } catch (Exception e) {
            throw new IllegalStateException(e);
        }
    }
}
